import { execSync } from "node:child_process";
import { expect, test, type APIRequestContext, type Page } from "@playwright/test";
import { authenticator } from "otplib";
import { ADMIN, API, CONTEXT, ESPORTS, WEB, masterStepUp, masterToken, signUpByPhone, smsCode, testPhone } from "./helpers";

/**
 * M21 in k3d: the esports player loop, end to end.
 *  1. Two players sign up on kriraghor.com and, on esports.kriraghor.com (same account), add a Free Fire
 *     UID with a screenshot. A reviewer (staff with approve_listings, made by the master) approves both.
 *  2. The master drafts a ৳50 solo tournament (1st ৳50, 2nd ৳20, ৳5 per kill); the reviewer approves it
 *     (the author cannot approve their own).
 *  3. Both players register and pay on the SSLCommerz simulator, and come back to esports.
 *  4. They check in; the master sets the room; the room page waits, then shows the credentials.
 *  5. The master posts results; the dispute window closes; the master finalises with step-up.
 *  6. The winner sees ৳65 on /me/winnings, and withdrawing asks for NID KYC.
 * The lifecycle job decides from stored times, so the test moves them in the dev database (in-cluster,
 * dev only) and waits for the next minute's tick, as the backend's Postman runner does.
 */
const JPEG = (tag: string) => Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.from(`e2e-${tag}-${Date.now()}`)]);
const shot = (page: Page, name: string) => page.screenshot({ path: `test-results/esports-${name}.png`, fullPage: true });

/** One SQL statement on the dev database (k3d only). Values are generated by this test, never user input. */
function sql(statement: string): string {
  return execSync(`kubectl --context ${CONTEXT} -n kriraghor-data exec postgres-0 -- psql -U kriraghor -d kriraghor -tAc "${statement}"`, { encoding: "utf8" }).trim();
}

/** A staff member with approve_listings, signed in to the admin API (TOTP enrolled on first login). */
async function reviewerToken(request: APIRequestContext, page: Page, masterTok: string): Promise<string> {
  const phone = testPhone();
  const { userId } = await signUpByPhone(page, WEB, phone, "E2E Reviewer");
  const made = await request.post(`${API}/admin/staff`, {
    headers: { Authorization: `Bearer ${masterTok}`, Origin: ADMIN, "X-Step-Up": await masterStepUp(request, page, masterTok, "staff.write") },
    data: { userId, employeeId: `KG-E2E-${Date.now()}`, permissions: ["approve_listings"] },
  });
  expect(made.status()).toBe(201);
  const headers = { Origin: ADMIN };
  await page.waitForTimeout(61_000); // one login code per minute after the signup code
  expect((await request.post(`${API}/auth/otp/send`, { data: { target: phone, purpose: "login" } })).status()).toBe(202);
  const login = await (await request.post(`${API}/auth/admin/login`, { headers, data: { target: phone, code: smsCode(phone) } })).json();
  expect(login.status).toBe("two_factor_setup_required");
  const { secret } = await (await request.post(`${API}/auth/2fa/totp/setup`, { headers, data: { challengeToken: login.challengeToken } })).json();
  const on = await request.post(`${API}/auth/2fa/totp/activate`, { headers, data: { challengeToken: login.challengeToken, code: authenticator.generate(secret) } });
  expect(on.ok()).toBeTruthy();
  return (await on.json()).accessToken as string;
}

/** Claim, tick and approve the open submission of a subject on the Moderation desk. */
async function approve(request: APIRequestContext, token: string, kind: string, subjectId: string) {
  const h = { Authorization: `Bearer ${token}`, Origin: ADMIN };
  const queue = await (await request.get(`${API}/admin/submissions?status=pending_review&kind=${kind}`, { headers: h })).json();
  const item = queue.items.find((s: { subjectId: string }) => s.subjectId === subjectId);
  expect(item).toBeTruthy();
  const sub = await (await request.post(`${API}/admin/submissions/${item.id}/claim`, { headers: h })).json();
  expect(sub.checks.filter((c: { result: string }) => c.result === "fail")).toEqual([]);
  await request.put(`${API}/admin/submissions/${item.id}/ticks`, { headers: h, data: { ticks: sub.rubric.items.map((i: { key: string }) => i.key) } });
  const d = await request.post(`${API}/admin/submissions/${item.id}/decide`, { headers: { ...h, "Idempotency-Key": `e2e-${Date.now()}-${subjectId}` }, data: { decision: "approve" } });
  expect(d.status()).toBe(200);
}

/** A player: signed up on kriraghor.com, then a Free Fire UID added on esports.kriraghor.com. */
async function player(page: Page, name: string, uid: string): Promise<{ userId: string }> {
  const { userId } = await signUpByPhone(page, WEB, testPhone(), name);
  await page.goto(`${ESPORTS}/me/esports`);
  const form = page.getByTestId("add-uid");
  await form.locator("select").first().selectOption({ label: "Free Fire" });
  await form.locator("#uid").fill(uid);
  await form.getByLabel("In-game name").fill(name.split(" ")[1]);
  await form.locator("#shot").setInputFiles({ name: "profile.jpg", mimeType: "image/jpeg", buffer: JPEG(uid) });
  await form.getByRole("button", { name: "Send for review" }).click();
  await expect(form.getByText("Sent for review")).toBeVisible();
  await expect(page.getByTestId("my-uids")).toContainText("In review");
  return { userId };
}

/** Register on esports, pay on the simulator (kriraghor.com), and come back to esports. */
async function registerAndPay(page: Page, slug: string) {
  await page.goto(`${ESPORTS}/t/${slug}/register`);
  await page.getByTestId("confirm-register").click();
  await expect(page).toHaveURL(new RegExp(`^${WEB}/pay/`));
  await page.getByRole("radio", { name: "bKash" }).check();
  await page.getByTestId("pay-button").click();
  await page.getByRole("button", { name: "Pay with bKash" }).click();
  await expect(page.getByTestId("pay-result")).toHaveAttribute("data-outcome", "paid");
  await page.getByTestId("back-to-esports").click();
  await expect(page).toHaveURL(`${ESPORTS}/me/matches`);
}

/** Wait for the lifecycle tick (every minute) to move the tournament to `status`. */
async function waitForStatus(request: APIRequestContext, slug: string, status: string) {
  await expect(async () => {
    expect((await (await request.get(`${API}/esports/tournaments/${slug}`)).json()).status).toBe(status);
  }).toPass({ timeout: 100_000, intervals: [5_000] });
}

test("UIDs, a reviewed tournament, paid entries, check-in, the room, results and prizes", async ({ browser, request }) => {
  test.setTimeout(15 * 60_000);
  const run = String(Date.now()).slice(-7);
  const ctxA = await browser.newContext();
  const ctxB = await browser.newContext();
  const ctxStaff = await browser.newContext();
  const a = await ctxA.newPage();
  const b = await ctxB.newPage();
  const staff = await ctxStaff.newPage();

  // 1. Players and UIDs; the reviewer approves them.
  const pa = await player(a, "E2E Rahim", `71${run}`);
  const pb = await player(b, "E2E Karim", `72${run}`);
  await shot(a, "uid-in-review");
  const master = await masterToken(request, staff);
  const reviewer = await reviewerToken(request, staff, master);
  const admin = { Authorization: `Bearer ${master}`, Origin: ADMIN };
  for (const p of [pa, pb]) {
    const profileId = sql(`SELECT id FROM esports_game_profiles WHERE user_id = '${p.userId}' AND status = 'pending'`);
    await approve(request, reviewer, "game_profile", profileId);
  }
  await expect(async () => {
    await a.goto(`${ESPORTS}/me/esports`);
    await expect(a.getByTestId("my-uids")).toContainText("Verified", { timeout: 2000 });
  }).toPass({ timeout: 60_000 });

  // 2. The tournament: drafted by the master, approved by the reviewer.
  const games = await (await request.get(`${API}/esports/games`)).json();
  const ff = games.items.find((g: { key: string }) => g.key === "free_fire");
  const solo = ff.modes.find((m: { key: string }) => m.key === "solo");
  const created = await request.post(`${API}/admin/esports/tournaments`, {
    headers: admin,
    data: {
      gameId: ff.id,
      modeId: solo.id,
      titleEn: `E2E Free Fire Daily ${run}`,
      titleBn: `ই২ই ফ্রি ফায়ার ডেইলি ${run}`,
      tier: "daily",
      format: "single_match",
      entryFee: 5000,
      maxSlots: 4,
      minParticipants: 2,
      prizes: [{ place: 1, amount: 5000 }, { place: 2, amount: 2000 }],
      killReward: 500,
      pointsPresetId: ff.presets[0].id,
      registrationOpensAt: new Date(Date.now() + 10 * 60_000).toISOString(),
      matches: [{ mapId: ff.maps[0].id, startsAt: new Date(Date.now() + 6 * 3_600_000).toISOString() }],
      rulesMd: "Mobile only.",
      featured: true,
    },
  });
  expect(created.status()).toBe(201);
  const t = await created.json();
  expect((await request.post(`${API}/admin/esports/tournaments/${t.id}/submit`, { headers: admin })).status()).toBe(200);
  await approve(request, reviewer, "esports_tournament", t.id);
  await waitForStatus(request, t.slug, "scheduled");

  // 3. Registration opens; both pay and come back to esports.
  sql(`UPDATE esports_tournaments SET registration_opens_at = now() - interval '1 hour' WHERE id = '${t.id}'`);
  await waitForStatus(request, t.slug, "registration_open");
  await a.goto(`${ESPORTS}/t/${t.slug}`);
  await expect(a.getByTestId("prize-table")).toContainText("৳50");
  await shot(a, "tournament");
  await registerAndPay(a, t.slug);
  await registerAndPay(b, t.slug);
  await expect(a.getByTestId("my-entries")).toContainText("Confirmed");

  // 4. Check-in, then the room: hidden until the reveal, then shown.
  sql(`UPDATE esports_tournaments SET registration_closes_at = now() - interval '1 minute' WHERE id = '${t.id}'`);
  await waitForStatus(request, t.slug, "registration_closed");
  sql(`UPDATE esports_stages SET checkin_opens_at = now() - interval '10 minutes', checkin_closes_at = now() + interval '20 minutes' WHERE tournament_id = '${t.id}'`);
  await waitForStatus(request, t.slug, "check_in");
  for (const page of [a, b]) {
    await page.goto(`${ESPORTS}/me/matches`);
    await page.getByTestId("check-in").click();
    await expect(page.getByText("Checked in.")).toBeVisible();
  }
  const matchId = t.matches?.[0]?.id ?? sql(`SELECT id FROM esports_matches WHERE tournament_id = '${t.id}'`);
  const roomSet = await request.put(`${API}/admin/esports/matches/${matchId}/room`, { headers: admin, data: { roomId: `845${run}`, password: "kgE2E" } });
  expect(roomSet.status()).toBe(200);
  expect(JSON.stringify(await roomSet.json())).not.toContain("kgE2E");
  await a.goto(`${ESPORTS}/me/matches/${matchId}/room`);
  await expect(a.getByText("The room opens shortly")).toBeVisible();
  sql(`UPDATE esports_room_credentials SET reveal_at = now() - interval '1 second' WHERE match_id = '${matchId}' AND status = 'scheduled'`);
  await expect(async () => {
    await a.reload();
    await expect(a.getByTestId("room-password")).toHaveText("kgE2E", { timeout: 3000 });
  }).toPass({ timeout: 100_000, intervals: [5_000] });
  await expect(a.getByTestId("room-id")).toHaveText(`845${run}`);
  await shot(a, "room");

  // 5. Results, the dispute window, finalise with step-up.
  sql(`UPDATE esports_stages SET checkin_closes_at = now() - interval '2 seconds' WHERE tournament_id = '${t.id}'`);
  sql(`UPDATE esports_matches SET starts_at = now() - interval '1 minute' WHERE tournament_id = '${t.id}'`);
  sql(`UPDATE esports_tournaments SET starts_at = now() - interval '1 minute' WHERE id = '${t.id}'`);
  const regA = sql(`SELECT registration_id FROM esports_registration_players WHERE user_id = '${pa.userId}' AND tournament_id = '${t.id}'`);
  const regB = sql(`SELECT registration_id FROM esports_registration_players WHERE user_id = '${pb.userId}' AND tournament_id = '${t.id}'`);
  const rows = [
    { registrationId: regA, placement: 1, kills: [{ userId: pa.userId, kills: 3 }] },
    { registrationId: regB, placement: 2, kills: [{ userId: pb.userId, kills: 1 }] },
  ];
  expect((await request.put(`${API}/admin/esports/matches/${matchId}/results`, { headers: admin, data: { rows } })).status()).toBe(200);
  expect((await request.post(`${API}/admin/esports/matches/${matchId}/results/post`, { headers: admin })).status()).toBe(200);
  await a.goto(`${ESPORTS}/t/${t.slug}`);
  await expect(a.getByTestId("standings")).toContainText("Rahim");
  sql(`UPDATE esports_matches SET dispute_closes_at = now() - interval '1 second' WHERE id = '${matchId}'`);
  await expect(async () => {
    const preview = await (await request.get(`${API}/admin/esports/tournaments/${t.id}/finalise-preview`, { headers: admin })).json();
    expect(preview).toMatchObject({ finalisable: true, totals: { collected: { amount: 10000 }, paid: { amount: 9000 }, revenue: { amount: 1000 } } });
  }).toPass({ timeout: 100_000, intervals: [5_000] });
  const fin = await request.post(`${API}/admin/esports/tournaments/${t.id}/finalise`, {
    headers: { ...admin, "X-Step-Up": await masterStepUp(request, staff, master, "esports.money"), "Idempotency-Key": `e2e-fin-${run}` },
  });
  expect(fin.status()).toBe(200);
  expect(await fin.json()).toMatchObject({ status: "paid_out", settlement: { collected: 10000, paid: 9000, fee: 1000 } });

  // 6. The winner's balance, and withdrawing asks for NID KYC.
  await a.goto(`${ESPORTS}/me/winnings`);
  await expect(a.getByTestId("winnings")).toContainText("৳65");
  await a.getByTestId("withdraw").click();
  await expect(a.getByRole("link", { name: "Verify your NID" })).toHaveAttribute("href", `${WEB}/account/verification`);
  await shot(a, "winnings");
  const ledger = await (await request.get(`${API}/admin/ledger/invariants`, { headers: admin })).json();
  expect(ledger.ok).toBe(true);

  // The admin desk shows it paid out; kriraghor.com's home has the esports strip.
  await staff.goto(`${WEB}/`);
  await expect(staff.getByTestId("esports-strip")).toBeVisible();
  await shot(staff, "web-home-strip");
  await Promise.all([ctxA.close(), ctxB.close(), ctxStaff.close()]);
});
